/**
 * Main Generator Function
 * Returns a dynamically compiled 2-part roast combination.
 */
window.ROAST_LIBRARY.generateRoast = function(personalityId, scores) {
    // 1. Pick a random base roast from the determined personality array
    const baseArray = this.personalities[personalityId] || this.personalities.default;
    const baseRoast = baseArray[Math.floor(Math.random() * baseArray.length)];
    
    // 2. Determine potential contexts based on the scores
    let availableContexts = [];
    
    // Thresholds
    if (scores.saving < 15) availableContexts.push(this.contextual.lowSaving);
    if (scores.chaos > 25) availableContexts.push(this.contextual.highChaos);
    if (scores.food > 20 && personalityId !== 'foodie') availableContexts.push(this.contextual.highFood);
    if (scores.digital > 20 && personalityId !== 'goblin') availableContexts.push(this.contextual.highDigital);
    if (scores.impulse > 25 && personalityId !== 'impulse') availableContexts.push(this.contextual.highImpulse);

    // 3. Option to append a contextual roast (70% chance to append if contexts apply, makes it longer/funnier)
    let finalRoast = baseRoast;
    
    if (availableContexts.length > 0 && Math.random() > 0.3) {
        // Pick a random available context category
        const selectedContextArray = availableContexts[Math.floor(Math.random() * availableContexts.length)];
        // Pick a random string from that category
        const modifierRoast = selectedContextArray[Math.floor(Math.random() * selectedContextArray.length)];
        finalRoast = `${baseRoast} ${modifierRoast}`;
    }

    return finalRoast;
};